import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { homedir } from 'node:os';
import { resolve } from 'node:path';
const output=process.env.DPR_TEST_OUTPUT || resolve(homedir(), 'workspace/runs/daily-paper-reader/browser');
await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.DPR_TEST_URL||'http://127.0.0.1:5173/');
await page.locator('.paper-card').first().waitFor();
assert.equal(await page.locator('.paper-card').count(),26);
assert.equal(await page.locator('.preview').isVisible(),true);
const first=await page.locator('.paper-card.selected').getAttribute('data-paper-key');
await page.keyboard.press('j');
assert.notEqual(await page.locator('.paper-card.selected').getAttribute('data-paper-key'),first);
await page.getByRole('textbox',{name:'搜索论文'}).fill('no-such-paper-123');
assert.equal(await page.locator('.paper-card').count(),0);
await page.getByRole('textbox',{name:'搜索论文'}).fill('');
await page.getByRole('textbox',{name:'搜索论文'}).press('s');
assert.equal(await page.locator('dialog').count(),0);
await page.getByRole('textbox',{name:'搜索论文'}).fill('');
await page.getByRole('heading',{name:'论文收件箱'}).click();
await page.keyboard.press('s');
assert.equal(await page.locator('dialog').isVisible(),true);
await page.getByRole('button',{name:'关闭对话框'}).click();
await page.screenshot({path:output+'/desktop.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
await page.locator('.paper-select').first().click();
assert.equal(await page.locator('.preview').isVisible(),true);
await page.screenshot({path:output+'/mobile.png',fullPage:true});
await page.getByRole('button',{name:'关闭',exact:true}).click();
assert.equal(await page.locator('.preview').isVisible(),false);
assert.deepEqual(errors,[]);
await browser.close();
console.log('Browser checks passed: real catalog, keyboard, editing guard, auth gate, mobile drawer and overflow');
